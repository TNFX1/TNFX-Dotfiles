#!/usr/bin/env python3
"""LOCAL: Discord-like Steam (Millennium QuickCSS) and Spotify (Spicetify user.css).
Neither CEF window can be transparent (Steam XWayland -> black), so fake the blur: a blurred, darkened copy of the
wallpaper is embedded as a data: URI (steamloopback URL did not load) and shown behind Steam's panels; the UI is hue/saturation-shifted toward the theme."""
import base64, colorsys, json, os, subprocess, sys
STEAM_HUE = 212  # Steam's blue-grey UI hue (#1b2838 / #1a9fff)
SAT_MIN = 0.35   # shortcut: inverse saturate() on images clips vivid pixels below ~0.35; raise if art looks off
STATE = os.path.expanduser('~/.local/state/quickshell/user/generated')

colors = json.load(open(f'{STATE}/colors.json'))
rgb = lambda hx: tuple(int(hx[i:i+2], 16) for i in (1, 3, 5))
h, l, s = colorsys.rgb_to_hls(*(c / 255 for c in rgb(colors['primary'])))
rot = round((h * 360 - STEAM_HUE + 180) % 360 - 180)  # shortest way round, -180..180
sat = round(max(SAT_MIN, min(1.0, s)), 2)
sr, sg, sb = rgb(colors['surface'])

if len(sys.argv) > 1 and sys.argv[1] == '--test':
    assert -180 <= rot <= 180 and SAT_MIN <= sat <= 1; print(rot, sat, colors['primary']); sys.exit()

wallpaper = open(f'{STATE}/wallpaper/path.txt').read().strip()
jpg = subprocess.run(['magick', wallpaper, '-resize', '480x480^', '-blur', '0x10', '-quality', '75', 'jpg:-'],
                     check=True, capture_output=True).stdout

css = f"""/* generated by steam_quickcss.py from the wallpaper theme, do not edit */
html::before {{ content: ""; position: fixed; inset: 0; background: rgba({sr}, {sg}, {sb}, 0.6); pointer-events: none; }}
body {{ filter: hue-rotate({rot}deg) saturate({sat}); }}
img, video, canvas, [style*="background-image"] {{ filter: saturate({round(1 / sat, 3)}) hue-rotate({-rot}deg); }}
/* let the fake-blur show through Steam's own panels */
body, #root, div:not([style*="background-image"]), section, nav, header, footer, main {{ background-color: transparent !important; }}
/* Steam paints most panels with gradients (background-image), keep real art (inline background-image) */
div:not([style*="background-image"]):not([class*="Art"]):not([class*="Capsule"]):not([class*="Image"]):not([class*="Hero"]):not([class*="Logo"]):not([class*="Avatar"]):not([class*="Icon"]) {{ background-image: none !important; }}
html {{ background: url("data:image/jpeg;base64,{base64.b64encode(jpg).decode()}") center / cover no-repeat fixed !important; }}
"""
open(os.path.expanduser('~/.config/millennium/quick.css'), 'w').write(css)

# Spotify: same blurred wallpaper + same 0.6 surface layer; panels a little denser like Discord's
cr, cg, cb = rgb(colors['surface_container'])
hr, hg, hb = rgb(colors['surface_container_high'])
spotify = f"""/* generated by fakeblur_css.py from the wallpaper theme, do not edit */
html {{ background: url("data:image/jpeg;base64,{base64.b64encode(jpg).decode()}") center / cover no-repeat fixed !important; }}
html::before {{ content: ""; position: fixed; inset: 0; background: rgba({sr}, {sg}, {sb}, 0.6); pointer-events: none; }}
body, #main, .Root, .Root__top-container, .Root__globalNav, .Root__top-bar, .Root__now-playing-bar {{ background: transparent !important; }}
.Root__nav-bar, .Root__main-view, .Root__right-sidebar, .main-view-container, .main-view-container__scroll-node-child,
.os-viewport, .main-nowPlayingView-section, .main-nowPlayingView-coverArtContainer, .main-topBar-background {{ background-color: transparent !important; }}
/* something unnamed paints the whole window opaque; clear plain div backgrounds like on Steam (art uses inline background-image / img) */
div:not([style*="background-image"]) {{ background-color: transparent !important; }}
html body .Root__nav-bar > *, html body .Root__main-view, html body .Root__right-sidebar > * {{ background-color: rgba({cr}, {cg}, {cb}, 0.25) !important; }}
.main-entityHeader-backgroundColor, .main-actionBarBackground-background, .main-topBar-background, .before-scroll-node {{ background: transparent !important; }}
/* Spotify (encore) paints panels from these variables, not from class backgrounds */
.encore-dark-theme, .encore-dark-theme .encore-base-set {{
  --background-base: rgba({cr}, {cg}, {cb}, 0.3) !important;
  --background-highlight: rgba({hr}, {hg}, {hb}, 0.5) !important;
  --background-press: rgba({hr}, {hg}, {hb}, 0.65) !important;
  --background-tinted-base: rgba({hr}, {hg}, {hb}, 0.35) !important;
  --background-tinted-highlight: rgba({hr}, {hg}, {hb}, 0.5) !important;
  --background-elevated-base: rgba({hr}, {hg}, {hb}, 0.9) !important;
  --background-elevated-highlight: rgba({hr}, {hg}, {hb}, 0.95) !important;
}}
"""
open(os.path.expanduser('~/.config/spicetify/Themes/Matugen/user.css'), 'w').write(spotify)
