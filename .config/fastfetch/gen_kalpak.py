# Generates ~/.config/fastfetch/kalpak.svg: Atatürk's karakul kalpak drawn from hundreds of small lit curls.
import math, random, os
random.seed(1919)
W, H = 190, 150
L, R, TOP, BOT = 8, 182, 26, 132      # body box
CX, RX, RY = 95, 87, 12              # ellipse for top and bottom rims

def body_path():
    # slightly barrel-shaped sides, curved bottom rim following the head
    return (f"M{L+3},{BOT} C{L-1},{BOT-35} {L-2},{TOP+30} {L},{TOP} "
            f"A{RX},{RY} 0 0 1 {R},{TOP} "
            f"C{R+2},{TOP+30} {R+1},{BOT-35} {R-3},{BOT} "
            f"A{RX-3},{RY} 0 0 1 {L+3},{BOT} Z")

def curl(x, y, r, light, dark, w):
    a = random.uniform(0, 2*math.pi); sweep = random.uniform(3.0, 4.0)
    pts = []
    for i in range(7):
        t = a + sweep*i/6; rr = r*(1 - 0.35*i/6)  # tightening spiral
        pts.append((x + rr*math.cos(t), y + rr*math.sin(t)*0.85))
    d = "M" + " L".join(f"{px:.1f},{py:.1f}" for px, py in pts)
    return (f'<path d="{d}" transform="translate(0.9 1.1)" stroke="{dark}" stroke-width="{w+0.6:.1f}"/>'
            f'<path d="{d}" stroke="{light}" stroke-width="{w:.1f}"/>')

side, top = [], []
for _ in range(1500):
    x = random.uniform(L-4, R+4); y = random.uniform(TOP-2, BOT+12)
    # brighter toward the lit left-center, dim at the edges (cylinder)
    u = (x - L) / (R - L); lit = max(0.0, 1 - abs(u - 0.38) * 2.2)
    g = int(58 + 70*lit + random.uniform(-10, 10))
    side.append(curl(x, y, random.uniform(2.2, 3.4), f"rgb({g},{g},{g+6})", "#050506", random.uniform(1.6, 2.2)))
for _ in range(350):
    a = random.uniform(0, 2*math.pi); k = math.sqrt(random.random())
    x = CX + RX*k*math.cos(a); y = TOP + RY*k*math.sin(a)
    g = int(105 + 50*(1 - k) + random.uniform(-12, 12))
    top.append(curl(x, y, random.uniform(2.2, 3.4), f"rgb({g},{g},{g+6})", "#141416", 1.6))

edge = []
# curls poking past the silhouette so the outline reads as fur, not a cut-out
for i in range(70):
    a = math.pi + math.pi*i/69  # back half of the top rim
    edge.append(curl(CX + RX*math.cos(a), TOP + RY*math.sin(a), random.uniform(1.8, 2.6), "rgb(120,120,128)", "#08080a", 1.5))
for i in range(36):
    y = TOP + (BOT-TOP)*i/35
    for x, g in ((L-0.5, 40), (R+0.5, 34)):
        edge.append(curl(x, y, random.uniform(1.8, 2.6), f"rgb({g},{g},{g+4})", "#030304", 1.6))

svg = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}" viewBox="0 0 {W} {H}">
  <!-- Atatürk's Milli Mücadele kalpak: black karakul fur, flat top. Generated by gen_kalpak.py -->
  <defs>
    <clipPath id="b"><path d="{body_path()}"/></clipPath>
    <clipPath id="t"><ellipse cx="{CX}" cy="{TOP}" rx="{RX}" ry="{RY}"/></clipPath>
    <linearGradient id="cyl" x1="0" y1="0" x2="1" y2="0">
      <stop offset="0" stop-color="#000" stop-opacity="0.85"/>
      <stop offset="0.18" stop-color="#000" stop-opacity="0.3"/>
      <stop offset="0.38" stop-color="#000" stop-opacity="0"/>
      <stop offset="0.7" stop-color="#000" stop-opacity="0.35"/>
      <stop offset="1" stop-color="#000" stop-opacity="0.9"/>
    </linearGradient>
    <linearGradient id="vert" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#000" stop-opacity="0.45"/>
      <stop offset="0.12" stop-color="#000" stop-opacity="0"/>
      <stop offset="0.8" stop-color="#000" stop-opacity="0.1"/>
      <stop offset="1" stop-color="#000" stop-opacity="0.65"/>
    </linearGradient>
    <radialGradient id="sheen" cx="0.4" cy="0.35" r="0.6">
      <stop offset="0" stop-color="#cfd3ff" stop-opacity="0.16"/>
      <stop offset="1" stop-color="#cfd3ff" stop-opacity="0"/>
    </radialGradient>
    <filter id="soft"><feGaussianBlur stdDeviation="3"/></filter>
  </defs>
  <!-- contact shadow on the head -->
  <ellipse cx="{CX}" cy="{BOT+4}" rx="{RX+2}" ry="7" fill="#000" opacity="0.55" filter="url(#soft)"/>
  <g clip-path="url(#b)" fill="none" stroke-linecap="round" stroke-linejoin="round">
    <path d="{body_path()}" fill="#141416" stroke="none"/>
    {"".join(side)}
    <rect width="{W}" height="{H}" fill="url(#cyl)" stroke="none"/>
    <rect width="{W}" height="{H}" fill="url(#vert)" stroke="none"/>
    <rect width="{W}" height="{H}" fill="url(#sheen)" stroke="none"/>
  </g>
  <g clip-path="url(#t)" fill="none" stroke-linecap="round" stroke-linejoin="round">
    <ellipse cx="{CX}" cy="{TOP}" rx="{RX}" ry="{RY}" fill="#2a2a2e" stroke="none"/>
    {"".join(top)}
  </g>
  <g fill="none" stroke-linecap="round" stroke-linejoin="round">{"".join(edge)}</g>
  <!-- crisp rim light where the top meets the sides -->
  <path d="M{L},{TOP} A{RX},{RY} 0 0 0 {R},{TOP}" fill="none" stroke="#e6e8ff" stroke-opacity="0.28" stroke-width="1.4"/>
</svg>'''
open(os.path.expanduser("~/.config/fastfetch/kalpak.svg"), "w").write(svg)
